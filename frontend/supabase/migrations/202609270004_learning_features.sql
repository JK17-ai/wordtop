create or replace function public.wordtop_record_answer(event_id uuid,catalog_id text,selected_meaning text,response_ms integer)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare owner_id uuid; expected_meaning text; result text; prior public.verified_answers%rowtype;
 run public.verified_streaks%rowtype; badge text;
begin
 select profile_id into owner_id from public.profile_accounts where auth_user_id=auth.uid();
 if owner_id is null then raise exception '프로필 연결이 필요합니다.'; end if;
 if event_id is null or response_ms is null or response_ms not between 0 and 10000 or length(selected_meaning)>4000 then raise exception '잘못된 답안입니다.'; end if;
 perform pg_advisory_xact_lock(hashtextextended('wordtop-awards:'||owner_id::text,0));
 select * into prior from public.verified_answers a where a.id=event_id;
 if found then
   if prior.profile_id<>owner_id or prior.catalog_id is distinct from catalog_id or prior.selected_meaning is distinct from selected_meaning or prior.response_ms<>response_ms then raise exception '답안 ID가 일치하지 않습니다.'; end if;
   return jsonb_build_object('accepted',true,'duplicate',true,'outcome',prior.outcome);
 end if;
 select c.meaning into expected_meaning from public.learning_catalog c where c.id=catalog_id;
 if not found then raise exception '등록되지 않은 단어입니다.'; end if;
 result:=case when selected_meaning is null then 'timeout' when response_ms>=10000 then 'timeout' when selected_meaning=expected_meaning then 'correct' else 'wrong' end;
 insert into public.verified_answers(id,profile_id,catalog_id,selected_meaning,response_ms,outcome)
 values(event_id,owner_id,catalog_id,selected_meaning,response_ms,result);
 insert into public.verified_streaks(profile_id) values(owner_id) on conflict do nothing;
 if result='correct' then
   update public.verified_streaks set correct_count=correct_count+1 where profile_id=owner_id returning * into run;
   badge:=case run.correct_count when 10 then 'bronze' when 20 then 'silver' when 30 then 'gold' else null end;
   if badge is not null then insert into public.earned_badges(profile_id,run_id,tier,answer_id) values(owner_id,run.run_id,badge,event_id) on conflict do nothing; end if;
 else
   update public.verified_streaks set correct_count=0,run_id=gen_random_uuid() where profile_id=owner_id returning * into run;
 end if;
 return jsonb_build_object('accepted',true,'outcome',result,'streak',run.correct_count,'badge',badge);
end; $$;

create or replace function public.wordtop_my_awards() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare owner_id uuid;
begin
 select profile_id into owner_id from public.profile_accounts where auth_user_id=auth.uid();
 if owner_id is null then raise exception '프로필 연결이 필요합니다.'; end if;
 return jsonb_build_object('streak',coalesce((select correct_count from public.verified_streaks where profile_id=owner_id),0),
 'awards',coalesce((select jsonb_agg(jsonb_build_object('id',id,'tier',tier,'awarded_at',awarded_at) order by awarded_at desc) from public.earned_badges where profile_id=owner_id),'[]'::jsonb));
end; $$;

create or replace function public.wordtop_family_overview() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare family uuid;
begin
 select p.family_id into family from public.profile_accounts a join public.profiles p on p.id=a.profile_id where a.auth_user_id=auth.uid();
 if family is null then raise exception '프로필 연결이 필요합니다.'; end if;
 return (select coalesce(jsonb_agg(jsonb_build_object('id',p.id,'name',p.name,'avatar',p.avatar,
 'total',coalesce(jsonb_array_length(s.snapshot->'deck'->'words'),0),
 'mastered',(select count(*) from jsonb_array_elements(s.snapshot->'deck'->'words') w where w->>'status'='mastered'),
 'scrap',(select count(*) from jsonb_array_elements(s.snapshot->'deck'->'words') w where w->>'status'='scrap'),
 'today_total',case when s.snapshot->'accuracy'->>'date'=to_char(now() at time zone 'Asia/Seoul','YYYY-MM-DD') then coalesce(s.snapshot->'accuracy'->'total','0'::jsonb) else '0'::jsonb end,
 'today_correct',case when s.snapshot->'accuracy'->>'date'=to_char(now() at time zone 'Asia/Seoul','YYYY-MM-DD') then coalesce(s.snapshot->'accuracy'->'correct','0'::jsonb) else '0'::jsonb end,
 'active_ms',coalesce(s.snapshot->'activeMs','0'::jsonb),'updated_at',s.updated_at,
 'badges',(select count(*) from public.earned_badges b where b.profile_id=p.id)) order by p.name),'[]'::jsonb)
 from public.profiles p left join public.study_sync_snapshots s on s.profile_id=p.id where p.family_id=family);
end; $$;
revoke all on function public.wordtop_record_answer(uuid,text,text,integer), public.wordtop_my_awards(), public.wordtop_family_overview() from public,anon;
grant execute on function public.wordtop_record_answer(uuid,text,text,integer), public.wordtop_my_awards(), public.wordtop_family_overview() to authenticated;
